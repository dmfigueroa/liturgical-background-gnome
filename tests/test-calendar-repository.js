import GLib from 'gi://GLib';
import Gio from 'gi://Gio';
import {CalendarRepository} from '../src/calendar/calendar-repository.js';
import {loadContents, makeDirectory, replaceContents} from '../src/utils/async.js';
import {calendar, day, assert, equal} from './helpers.js';
const valid = calendar([day('2026-08-22', 'white'), {...day('2026-08-23'), celebration: {rank: null, names: []}}]);
const temp = GLib.dir_make_tmp('liturgical-tests-XXXXXX');
const fixedNow = () => GLib.DateTime.new_from_iso8601('2026-08-22T12:00:00Z', null);
let seenEtag = null;
const client = {fetch: async etag => { seenEtag = etag; return {status: 200, calendar: valid, etag: '"one"'}; }};
let repo = new CalendarRepository({client, dataDir: temp, now: fixedNow}); await repo.load(); await repo.refresh();
equal(repo.state.calendar.days.length, 2); equal(repo.state.etag, '"one"'); equal(seenEtag, null);
repo = new CalendarRepository({client: {fetch: async etag => { seenEtag = etag; return {status: 304}; }}, dataDir: temp, now: fixedNow});
await repo.load(); await repo.refresh(); equal(seenEtag, '"one"'); equal(repo.state.calendar.days.length, 2);
const before = await loadContents(repo.file);
repo.client = {fetch: async () => ({status: 200, calendar: {bad: true}, etag: 'bad'})};
let failed = false; try { await repo.refresh(); } catch { failed = true; } assert(failed); equal(await loadContents(repo.file), before, 'invalid response changed cache');
repo.client = {fetch: async () => { throw new Error('offline'); }}; failed = false; try { await repo.refresh(); } catch { failed = true; } assert(failed); equal(repo.state.etag, '"one"');
const malformedDir = GLib.dir_make_tmp('liturgical-malformed-XXXXXX'); const directory = Gio.File.new_for_path(malformedDir); await makeDirectory(directory);
await replaceContents(directory.get_child('calendar-cache.json'), '{bad json'); repo = new CalendarRepository({dataDir: malformedDir}); await repo.load(); equal(repo.state.calendar, null);
print('calendar repository tests passed');
